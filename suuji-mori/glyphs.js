// 1画を 3 ずつの 等間隔の点に（なぞりの判定と 色ぬりに使う）
const STEP = 3;
function strokePts(str){
  const raw = [];
  for (const t of str.match(/[MLQA][^MLQA]*/g)){
    const k = t[0], a = t.slice(1).trim().split(/[\s,]+/).map(Number);
    if (k === 'M' || k === 'L') raw.push([a[0], a[1]]);
    else if (k === 'Q'){
      const [x0, y0] = raw[raw.length-1];
      for (let i=1;i<=20;i++){ const u = i/20, v = 1-u; raw.push([v*v*x0 + 2*v*u*a[0] + u*u*a[2], v*v*y0 + 2*v*u*a[1] + u*u*a[3]]); }
    } else {
      const [cx, cy, rx, ry, a0, a1] = a, m = Math.ceil(Math.abs(a1-a0)/5);
      for (let i=0;i<=m;i++){ const r = (a0 + (a1-a0)*i/m) * Math.PI/180; raw.push([cx + rx*Math.cos(r), cy + ry*Math.sin(r)]); }
    }
  }
  const out = [raw[0]]; let carry = 0;
  for (let i=1;i<raw.length;i++){
    const [x0, y0] = raw[i-1], [x1, y1] = raw[i], d = Math.hypot(x1-x0, y1-y0);
    let s = STEP - carry;
    while (s <= d){ out.push([x0 + (x1-x0)*s/d, y0 + (y1-y0)*s/d]); s += STEP; }
    carry = d - (s - STEP);
  }
  const last = raw[raw.length-1], end = out[out.length-1];
  if (Math.hypot(last[0]-end[0], last[1]-end[1]) > .5) out.push(last);
  return out;
}
